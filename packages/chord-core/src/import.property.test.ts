import { describe, expect, it } from "vitest";
import { importText } from "./import";
import type { RtlColumns } from "./import";
import { parseSong } from "./song";

/** Deterministic PRNG (mulberry32): the same seed always yields the same input. */
function rng(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

type Rand = () => number;
const int = (r: Rand, lo: number, hi: number): number =>
  lo + Math.floor(r() * (hi - lo + 1));
const pick = <T>(r: Rand, xs: readonly T[]): T => xs[int(r, 0, xs.length - 1)]!;

const CHORDS = ["C", "Am", "G", "G/B", "Dm7", "F#m", "Fmaj7", "Em", "D", "Bb"];
const HEBREW_BASE = Array.from({ length: 27 }, (_, i) =>
  String.fromCodePoint(0x05d0 + i),
);
// True combining marks only: cantillation U+0591-05AF, points U+05B0-05BD, U+05BF,
// U+05C1-05C2, U+05C4-05C5, U+05C7. Excludes maqaf U+05BE and the punctuation U+05C0,
// U+05C3, U+05C6, which are not marks (hebrew-rtl-chords B10).
const HEBREW_MARKS: string[] = [];
for (let cp = 0x0591; cp <= 0x05c7; cp++) {
  if ([0x05be, 0x05c0, 0x05c3, 0x05c6].includes(cp)) continue;
  HEBREW_MARKS.push(String.fromCodePoint(cp));
}
const LATIN = "abdefghklmnoprstuvwy".split("");

function hebrewWord(r: Rand): string {
  let w = "";
  for (let i = int(r, 2, 6); i > 0; i--) {
    w += pick(r, HEBREW_BASE);
    for (let m = int(r, 0, 2) === 2 ? int(r, 1, 2) : 0; m > 0; m--) {
      w += pick(r, HEBREW_MARKS); // only ever after a base letter
    }
  }
  return w;
}

function latinWord(r: Rand): string {
  let w = "";
  for (let i = int(r, 3, 7); i > 0; i--) w += pick(r, LATIN);
  return w;
}

function lyricLine(r: Rand): string {
  const mode = int(r, 0, 2); // 0 Hebrew, 1 Latin, 2 mixed
  const words: string[] = [];
  for (let i = int(r, 1, 5); i > 0; i--) {
    words.push(
      mode === 0 || (mode === 2 && r() < 0.5) ? hebrewWord(r) : latinWord(r),
    );
  }
  return words.join(" ".repeat(int(r, 1, 2)));
}

interface Generated {
  text: string;
  /** Chord tokens on chord lines (every chord line is generated by this function). */
  chordCount: number;
}

function generate(seed: number): Generated {
  const r = rng(seed);
  const lines: string[] = [];
  let chordCount = 0;
  const blocks = int(r, 1, 4);
  for (let b = 0; b < blocks; b++) {
    if (r() < 0.3) lines.push("# a comment");
    let chordLine = " ".repeat(int(r, 0, 3));
    const tokens = int(r, 1, 5);
    for (let t = 0; t < tokens; t++) {
      if (t > 0) chordLine += " ".repeat(int(r, 1, 6));
      chordLine += pick(r, CHORDS);
    }
    chordCount += tokens;
    lines.push(chordLine);
    if (r() < 0.85) lines.push(lyricLine(r));
    if (r() < 0.5) lines.push("");
  }
  return { text: lines.join("\n"), chordCount };
}

const SEEDS = Array.from({ length: 300 }, (_, i) => i + 1);
const MODES: RtlColumns[] = ["mirror", "logical"];

const chordsIn = (chordpro: string): string[] =>
  [...chordpro.matchAll(/\[([^\]]*)\]/g)].map((m) => m[1]!);

describe("importText properties (seeded)", () => {
  it("the generator is deterministic and varied", () => {
    expect(generate(7)).toEqual(generate(7));
    expect(new Set(SEEDS.map((s) => generate(s).text)).size).toBeGreaterThan(
      250,
    );
    expect(SEEDS.every((s) => generate(s).chordCount >= 1)).toBe(true);
  });

  it("the generator reaches combining marks and RTL lyrics, marks only after a letter", () => {
    const all = SEEDS.map((s) => generate(s).text).join("\n");
    expect(/[\u0591-\u05C7]/u.test(all)).toBe(true);
    expect(/[\u05D0-\u05EA]/u.test(all)).toBe(true);
    expect(/[\u05BE\u05C0\u05C3\u05C6]/u.test(all)).toBe(false);
    expect(
      /(?<![\u05D0-\u05EA])(?<![\u0591-\u05C7])[\u0591-\u05C7]/u.test(all),
    ).toBe(false);
  });

  for (const mode of MODES) {
    describe(`rtlColumns: ${mode}`, () => {
      it("never throws and converts every input", () => {
        for (const seed of SEEDS) {
          const { text } = generate(seed);
          const result = importText(text, { rtlColumns: mode });
          expect(result.format, `seed ${seed}`).toBe("chords-over-lyrics");
        }
      });

      it("the output parses without diagnostics", () => {
        for (const seed of SEEDS) {
          const { text } = generate(seed);
          const { chordpro } = importText(text, { rtlColumns: mode });
          expect(parseSong(chordpro).diagnostics, `seed ${seed}`).toEqual([]);
        }
      });

      it("places exactly the chords of the chord lines, none lost or invented", () => {
        for (const seed of SEEDS) {
          const { text, chordCount } = generate(seed);
          const { chordpro } = importText(text, { rtlColumns: mode });
          expect(chordsIn(chordpro).length, `seed ${seed}`).toBe(chordCount);
        }
      });

      it("re-importing the output is a chordpro passthrough with identical text", () => {
        for (const seed of SEEDS) {
          const { text } = generate(seed);
          const { chordpro } = importText(text, { rtlColumns: mode });
          const again = importText(chordpro, { rtlColumns: mode });
          expect(again.format, `seed ${seed}`).toBe("chordpro");
          expect(again.chordpro, `seed ${seed}`).toBe(chordpro);
        }
      });

      it("no chord splits a base letter from its mark", () => {
        for (const seed of SEEDS) {
          const { text } = generate(seed);
          const { chordpro } = importText(text, { rtlColumns: mode });
          expect(/\][\u0591-\u05C7]/u.test(chordpro), `seed ${seed}`).toBe(
            false,
          );
        }
      });
    });
  }
});

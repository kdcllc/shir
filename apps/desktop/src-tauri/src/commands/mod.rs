//! Tauri commands over the song database, plus the tauri-specta bindings export.
#![cfg_attr(
    not(test),
    deny(clippy::unwrap_used, clippy::expect_used, clippy::panic)
)]

pub mod state;

use crate::db::{repo, search, DbError, ErrorKind, SaveSongInput, SearchHit, Song, SongSummary};
use state::DbState;
use std::path::Path;
use tauri::State;
use tauri_specta::{collect_commands, Builder, ErrorHandlingMode};

/// Where the generated TypeScript bindings are committed.
pub const BINDINGS_PATH: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/../src/bindings.ts");

const HEADER: &str = "// This file is generated by tauri-specta. Do not edit by hand.\n\
// Regenerate: SHIR_UPDATE_BINDINGS=1 cargo test --manifest-path apps/desktop/src-tauri/Cargo.toml bindings_are_current";

pub fn save_song_impl(state: &DbState, input: &SaveSongInput) -> Result<Song, DbError> {
    state.with_conn(|c| repo::save_song(c, input))
}

pub fn get_song_impl(state: &DbState, id: &str) -> Result<Song, DbError> {
    state.with_conn(|c| repo::get_song(c, id))
}

pub fn list_songs_impl(state: &DbState) -> Result<Vec<SongSummary>, DbError> {
    state.with_conn(|c| repo::list_songs(c))
}

pub fn delete_song_impl(state: &DbState, id: &str) -> Result<(), DbError> {
    state.with_conn(|c| repo::delete_song(c, id))
}

pub fn search_songs_impl(state: &DbState, query: &str) -> Result<Vec<SearchHit>, DbError> {
    state.with_conn(|c| search::search_songs(c, query))
}

#[tauri::command(async)]
#[specta::specta]
pub fn save_song(state: State<'_, DbState>, input: SaveSongInput) -> Result<Song, DbError> {
    save_song_impl(&state, &input)
}

#[tauri::command(async)]
#[specta::specta]
pub fn get_song(state: State<'_, DbState>, id: String) -> Result<Song, DbError> {
    get_song_impl(&state, &id)
}

#[tauri::command(async)]
#[specta::specta]
pub fn list_songs(state: State<'_, DbState>) -> Result<Vec<SongSummary>, DbError> {
    list_songs_impl(&state)
}

#[tauri::command(async)]
#[specta::specta]
pub fn delete_song(state: State<'_, DbState>, id: String) -> Result<(), DbError> {
    delete_song_impl(&state, &id)
}

#[tauri::command(async)]
#[specta::specta]
pub fn search_songs(state: State<'_, DbState>, query: String) -> Result<Vec<SearchHit>, DbError> {
    search_songs_impl(&state, &query)
}

/// The tauri-specta builder: the five commands, `Result` error handling, and the
/// error types (so `ErrorKind` is present in TS even where only nested).
pub fn specta_builder() -> Builder<tauri::Wry> {
    Builder::<tauri::Wry>::new()
        .commands(collect_commands![
            save_song,
            get_song,
            list_songs,
            delete_song,
            search_songs
        ])
        .error_handling(ErrorHandlingMode::Result)
        .typ::<ErrorKind>()
        .typ::<DbError>()
}

/// Write the TypeScript bindings to `path`.
pub fn export_bindings(path: &Path) -> Result<(), String> {
    specta_builder()
        .export(
            specta_typescript::Typescript::default().header(HEADER),
            path,
        )
        .map_err(|e| e.to_string())
}

/// Debug-start sync: write the bindings only when they differ from the file on disk
/// (CRLF-normalized), so a dev start does not touch the file or trigger HMR.
pub fn sync_bindings(path: &Path) -> Result<(), String> {
    let tmp = std::env::temp_dir().join(format!("shir-bindings-{}.ts", std::process::id()));
    export_bindings(&tmp)?;
    let fresh = std::fs::read_to_string(&tmp).map_err(|e| e.to_string());
    let _ = std::fs::remove_file(&tmp);
    let fresh = fresh?;
    let current = std::fs::read_to_string(path).unwrap_or_default();
    if current.replace("\r\n", "\n") == fresh.replace("\r\n", "\n") {
        return Ok(());
    }
    std::fs::write(path, fresh).map_err(|e| e.to_string())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn input(chordpro: &str) -> SaveSongInput {
        SaveSongInput {
            id: None,
            chordpro: chordpro.into(),
        }
    }

    fn exported_ts() -> String {
        let dir = tempfile::tempdir().unwrap();
        let p = dir.path().join("b.ts");
        export_bindings(&p).unwrap();
        std::fs::read_to_string(p).unwrap()
    }

    #[test]
    fn round_trip_through_every_impl() {
        let st = DbState::in_memory();
        let saved = save_song_impl(&st, &input("{title: Hello}\n[C]La la")).unwrap();
        assert_eq!(saved.title, "Hello");
        assert_eq!(get_song_impl(&st, &saved.id).unwrap(), saved);
        let list = list_songs_impl(&st).unwrap();
        assert_eq!(list.len(), 1);
        assert_eq!(list[0].id, saved.id);
        let found = search_songs_impl(&st, "Hello").unwrap();
        assert_eq!(found.len(), 1);
        assert_eq!(found[0].song.id, saved.id);
        assert_eq!(found[0].snippet, None);
        delete_song_impl(&st, &saved.id).unwrap();
        assert_eq!(
            get_song_impl(&st, &saved.id).unwrap_err().kind,
            ErrorKind::NotFound
        );
        assert!(list_songs_impl(&st).unwrap().is_empty());
    }

    #[test]
    fn unavailable_state_fails_every_command() {
        let st = DbState::unavailable(DbError::storage("boom"));
        let errs = [
            save_song_impl(&st, &input("x")).unwrap_err(),
            get_song_impl(&st, "i").unwrap_err(),
            list_songs_impl(&st).unwrap_err(),
            delete_song_impl(&st, "i").unwrap_err(),
            search_songs_impl(&st, "q").unwrap_err(),
        ];
        for e in errs {
            assert_eq!(e.kind, ErrorKind::Unavailable);
            assert!(e.message.contains("boom"), "{}", e.message);
        }
    }

    #[test]
    fn poisoned_mutex_is_storage_error() {
        let st = DbState::in_memory();
        st.poison();
        let e = list_songs_impl(&st).unwrap_err();
        assert_eq!(e.kind, ErrorKind::Storage);
        assert!(e.message.contains("poisoned"));
    }

    #[test]
    fn open_failure_is_stored_not_returned() {
        let dir = tempfile::tempdir().unwrap();
        let bad = dir.path().join("shir.db");
        std::fs::create_dir(&bad).unwrap();
        let st = DbState::open(&bad);
        assert_eq!(
            list_songs_impl(&st).unwrap_err().kind,
            ErrorKind::Unavailable
        );
    }

    /// Field names of the `export const commands = { ... };` block.
    fn command_fields(ts: &str) -> Vec<String> {
        let start = ts.find("export const commands = {").unwrap();
        let rest = &ts[start..];
        let block = &rest[..rest.find("\n};").unwrap()];
        block
            .lines()
            .skip(1)
            .filter_map(|l| {
                let l = l.trim_start();
                let (name, after) = l.split_once(':')?;
                let name = name.trim_end_matches('"').trim_start_matches('"');
                let after = after.trim_start();
                let after = after.strip_prefix("async").unwrap_or(after).trim_start();
                (after.starts_with('(') && name.chars().all(|c| c.is_ascii_alphabetic()))
                    .then(|| name.to_string())
            })
            .collect()
    }

    #[test]
    fn exported_ts_has_exactly_the_five_commands() {
        let ts = exported_ts();
        let mut fields = command_fields(&ts);
        fields.sort();
        assert_eq!(
            fields,
            [
                "deleteSong",
                "getSong",
                "listSongs",
                "saveSong",
                "searchSongs"
            ],
            "{ts}"
        );
        assert_eq!(ts.matches("export const commands").count(), 1);
        for t in [
            "Song",
            "SongSummary",
            "SearchHit",
            "SaveSongInput",
            "Language",
            "ErrorKind",
            "DbError",
        ] {
            assert!(ts.contains(&format!("type {t} ")), "missing type {t}");
        }
        assert!(ts.contains("\"status\": \"ok\"") || ts.contains("status: \"ok\""));
        assert!(ts.starts_with("// This file is generated"));
    }

    #[test]
    fn sync_bindings_writes_only_on_difference() {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("bindings.ts");
        let fresh = exported_ts();
        assert!(fresh.contains('\n'));

        // (a) Same content with CRLF line endings: not rewritten.
        let crlf = fresh.replace('\n', "\r\n");
        std::fs::write(&path, &crlf).unwrap();
        sync_bindings(&path).unwrap();
        assert_eq!(std::fs::read_to_string(&path).unwrap(), crlf);

        // (b) Stale content: rewritten to the fresh export.
        std::fs::write(&path, "// stale\n").unwrap();
        sync_bindings(&path).unwrap();
        assert_eq!(std::fs::read_to_string(&path).unwrap(), fresh);

        // (c) Missing file: created.
        std::fs::remove_file(&path).unwrap();
        sync_bindings(&path).unwrap();
        assert_eq!(std::fs::read_to_string(&path).unwrap(), fresh);
    }

    #[test]
    fn bindings_are_current() {
        let fresh = exported_ts().replace("\r\n", "\n");
        if std::env::var("SHIR_UPDATE_BINDINGS").as_deref() == Ok("1") {
            std::fs::write(BINDINGS_PATH, &fresh).unwrap();
            return;
        }
        let current = std::fs::read_to_string(BINDINGS_PATH)
            .unwrap_or_default()
            .replace("\r\n", "\n");
        assert!(
            current == fresh,
            "apps/desktop/src/bindings.ts is stale. Regenerate with: SHIR_UPDATE_BINDINGS=1 cargo test --manifest-path apps/desktop/src-tauri/Cargo.toml bindings_are_current"
        );
    }
}
